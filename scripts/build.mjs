import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const version = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")).version;
const css = readFileSync(resolve(root, "src/style.css"), "utf8");
const modules = ["core", "adapter", "browser"].map(name =>
  readFileSync(resolve(root, `src/${name}.mjs`), "utf8")
    .replace(/^import .*;\n/gmu, "").replace(/^export /gmu, ""));
const header = `// ==UserScript==\n// @name Arc Command Bar\n// @version ${version}\n// @description Tab-first command bar for Zen Beta. Sine required.\n// @include chrome://browser/content/browser.xhtml\n// ==/UserScript==\n// MIT. Generated by scripts/build.mjs; edit src/, then rebuild.\n`;
writeFileSync(resolve(root, "arc-command-bar.uc.js"), `${header}(() => {\n"use strict";\nconst ARC_STYLE = ${JSON.stringify(css)};\n${modules.join("\n")}\n})();\n`);
console.log("Built arc-command-bar.uc.js (no dependencies).");
